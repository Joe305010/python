# Logical operators- They are used to check whether the expression is True or False
# They include the following
# Logical AND - Both are supposed to be true
# Logical NOT - Returns true if both are false
# Logical OR - Returns true if  one is true

a = True
b = False

# Logical AND
print(a and b)

# logical or
print(a and b)

# Logical NOT
print( not a)
print( not b)




